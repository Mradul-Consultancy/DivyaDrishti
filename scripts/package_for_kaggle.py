"""
Re-package the codebase into a fresh deepfake_code.zip for Kaggle upload.
Excludes data/, __pycache__/, .git/, *.pyc, staging_dataset/, kaggle_upload/, kaggle_kernel/
"""
import zipfile
import os
import sys
from pathlib import Path

# The Windows console uses cp1252, which cannot encode arrows or emoji.
# Force UTF-8 output so this script never crashes after doing its work.
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:  # pragma: no cover
    pass

REPO = Path(r'e:\deepfake')
OUT  = REPO / 'kaggle_upload' / 'deepfake_code.zip'
OUT.parent.mkdir(exist_ok=True)

EXCLUDES = {
    'data', '__pycache__', '.git', 'kaggle_upload', 'staging_dataset',
    'kaggle_kernel', 'runs', '.gitignore', 'node_modules', '.pytest_cache',
    'reports',  # don't ship toy reports; Kaggle will generate real ones
    'kaggle_acc_acc-gpu', 'kaggle_acc_acc-t4x2', 'kaggle_acc_acc-p100',
    'kaggle_diag', 'kaggle_bench', 'kaggle_gputest', 'kaggle_crops_ds',
    'kaggle_crops.zip', 'kaggle_data_ds', 'kaggle_ckpt_ds',
    'out_acc-gpu', 'out_acc-t4x2', 'out_acc-p100',
    'diag_out', 'diag_out2', 'gpu_out', 'bench_out', 'kaggle_pilot_out',
    'pilot_out2', 'pilot_pull', 'celebdf_out2', 'celebdf_pull2',
    # ImageNet weights ship as their own dataset: a 580 MB code dataset does
    # not materialise reliably on Kaggle, whereas small ones do.
    'pretrained',
    # Scratch trees left by earlier packaging / download runs. Each holds a
    # full revision of the codebase plus downloaded artefacts, and would
    # multiply the size of the package.
    'kaggle_artifacts', 'kaggle_art', 'kaggle_art2', 'kaggle_art3',
    'kaggle_art4', 'kaggle_art5', 'kaggle_art6', 'kaggle_art7',
    'kaggle_final', 'kaggle_final2', 'kaggle_final3', 'kaggle_out',
    'kaggle_ckpt_dfdc_ds', 'kaggle_pretrained_ds', 'kaggle_train',
    'kaggle_celebdf_kernel', 'kaggle_acc_gpu', 'kaggle_acc_NvidiaTeslaT4x2',
    'staging_dataset', 'train_out', 'train_out2', 'train_out3', 'train_out4',
    'train_out5', 'logs',
}
# NOTE: '.pt' is NOT excluded - the YOLO26n-cls pretrained checkpoint must
# ship with the code, otherwise YOLO training cannot start on Kaggle.
# '.pth' (torch checkpoints) is still excluded: those are large and are
# regenerated by the training run.
EXCLUDE_SUFFIXES = {'.pyc', '.pyo', '.log', '.tmp', '.pth', '.tar', '.gz'}
EXCLUDE_PARTS = {'checkpoints', '__pycache__', '.pytest_cache', '.git'}
EXCLUDE_FILES = {'deepfake_code.zip'}

count = 0
with zipfile.ZipFile(OUT, 'w', zipfile.ZIP_DEFLATED) as zf:
    for path in sorted(REPO.rglob('*')):
        # Skip directories themselves
        if path.is_dir():
            continue
        rel = path.relative_to(REPO)
        parts = rel.parts
        # Skip excluded top-level dirs
        if parts[0] in EXCLUDES:
            continue
        # Skip excluded directories anywhere in the path
        if any(p in EXCLUDE_PARTS for p in parts):
            continue
        if path.name in EXCLUDE_FILES:
            continue
        if path.suffix.lower() in EXCLUDE_SUFFIXES:
            continue
        # Skip hidden files and dirs
        if any(p.startswith('.') for p in parts):
            continue
        zf.write(path, rel)
        count += 1

size_kb = OUT.stat().st_size / 1024
print(f'Packaged {count} files → {OUT}  ({size_kb:.0f} KB)')

