"""
Tests that the shipped (fallback) checkpoints are actually trained.

The canonical paths `models/checkpoints/<model>_best.pth` are what the README
tells users to download from the GitHub Release and where the evaluation
pipeline looks when no domain-specific checkpoint exists.

They originally held epoch-1 warm-up weights, which score at chance
(ROC-AUC 0.49 / 0.47 / 0.46 on the Celeb-DF v2 test split) while looking
like a normal trained model on disk. These tests fail if that regresses:
a checkpoint that does not beat chance is not shippable.

Additionally, each test verifies the measured AUC against
``reports/shipped_checkpoint_probe.json`` (generated by
``scripts/probe_shipped_checkpoints.py`` and committed alongside the
release), so the released weights are tied to the published numbers instead
of merely beating chance. If you intentionally replace weights, regenerate
the probe so the record follows the artefact.
"""

import json
import sys
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.append(str(ROOT))

from scripts.probe_shipped_checkpoints import (
    PROBE_PATH,
    TOLERANCE,
    _score_resnet18,
    _score_timm,
)

import config


def _load_probe() -> dict:
    if not PROBE_PATH.exists():
        pytest.skip(
            f"{PROBE_PATH.name} not present - run scripts/probe_shipped_checkpoints.py "
            "to record the shipped checkpoint baseline"
        )
    return json.loads(PROBE_PATH.read_text(encoding="utf-8"))


def _assert_matches_probe(probe: dict, key: str, auc: float):
    entry = (probe.get("models") or {}).get(key)
    if not entry or entry.get("status") != "measured":
        pytest.skip(f"probe has no measured entry for {key}")
    recorded = entry["roc_auc"]
    assert abs(auc - recorded) <= TOLERANCE, (
        f"{key} measures ROC-AUC {auc:.4f} but the shipped probe record is "
        f"{recorded:.4f} (tolerance {TOLERANCE}). The released weights no longer "
        f"reproduce the published number - if the weights were replaced on "
        f"purpose, regenerate the record with "
        f"`python scripts/probe_shipped_checkpoints.py`."
    )


def _celebdf_test_dir():
    d = config.PROCESSED_CELEBDF_DIR / "test"
    if not (d / "real").exists() or not (d / "fake").exists():
        pytest.skip("Celeb-DF test split not extracted")
    return d


class TestShippedCheckpointsAreTrained:
    @pytest.mark.parametrize("model_name", [
        "efficientnet_b3.ra2_in1k",
        "convnext_tiny.fb_in22k_ft_in1k",
    ])
    def test_fallback_checkpoint_beats_chance(self, model_name):
        ckpt = config.CHECKPOINT_DIR / f"{model_name}_best.pth"
        if not ckpt.exists():
            pytest.skip(f"{ckpt.name} not present")
        auc = _score_timm(model_name, ckpt, _celebdf_test_dir())["roc_auc"]
        assert auc > 0.60, (
            f"{ckpt.name} scores ROC-AUC {auc:.4f} on the Celeb-DF v2 test split - "
            "a checkpoint that does not clearly beat chance must not be shipped."
        )
        _assert_matches_probe(_load_probe(), model_name, auc)

    def test_resnet18_fallback_beats_chance(self):
        ckpt = config.CHECKPOINT_DIR / "resnet18_best.pth"
        if not ckpt.exists():
            pytest.skip("resnet18_best.pth not present")
        auc = _score_resnet18(ckpt, _celebdf_test_dir())["roc_auc"]
        assert auc > 0.60, (
            f"resnet18_best.pth scores ROC-AUC {auc:.4f} on the Celeb-DF v2 test "
            "split - a checkpoint that does not clearly beat chance must not be shipped."
        )
        _assert_matches_probe(_load_probe(), "resnet18", auc)

    def test_fallback_matches_a_per_domain_checkpoint(self):
        """
        The fallback path must hold the same weights as one of the
        per-domain checkpoints, not a superseded warm-up copy.
        """
        for model_name in ("efficientnet_b3.ra2_in1k", "convnext_tiny.fb_in22k_ft_in1k",
                           "resnet18"):
            fallback = config.CHECKPOINT_DIR / f"{model_name}_best.pth"
            per_domain = config.CHECKPOINT_DIR / "celebdf" / f"{model_name}_best.pth"
            if not (fallback.exists() and per_domain.exists()):
                pytest.skip(f"{model_name} checkpoints not present")
            import torch
            a = torch.load(fallback, map_location="cpu")["state_dict"]
            b = torch.load(per_domain, map_location="cpu")["state_dict"]
            same = a.keys() == b.keys() and all(
                torch.equal(a[k], b[k]) for k in a
            )
            assert same, (
                f"models/checkpoints/{model_name}_best.pth differs from the "
                "per-domain Celeb-DF checkpoint - the fallback copy is stale."
            )
